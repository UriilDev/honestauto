export function carImages(car: Car) {
  const photoSet = carPhotoFolders[car.slug]
  const count = (imageCounts as Record<string, number>)[car.slug] ?? car.imageCount
  if (!photoSet) return []
  return Array.from({ length: count }, (_, i) => `/images/${photoSet.folder}/${photoSet.prefix}${i + 1}.${photoSet.extension}`)
}

